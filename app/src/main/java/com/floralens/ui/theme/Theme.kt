/**
 * FloraLens theme.
 *
 * The app is light-first (cream/sage). [darkTheme] is forced `true` on the
 * camera / Identify screen regardless of system setting — matching the
 * design system's "dark scheme — camera screen" spec.
 */
@Composable
fun FloraLensTheme(
    darkTheme: Boolean = false,
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = FloraLensTypography,
        shapes = FloraLensShapes,
        content = content,
    )
}
